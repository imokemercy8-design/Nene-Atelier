function offsetIsoDate(daysFromToday: number): string {
  const dt = new Date();
  dt.setDate(dt.getDate() + daysFromToday);
  const yyyy = dt.getFullYear();
  const mm = String(dt.getMonth() + 1).padStart(2, '0');
  const dd = String(dt.getDate()).padStart(2, '0');
  return `${yyyy}-${mm}-${dd}`;
}

