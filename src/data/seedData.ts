export function calculateProductUnitPrice(
  product: Product,
  length?: string,
  laceType?: string,
  density?: string
): number {
  let price = product.basePrice;
  if (product.category === 'Wigs') {
    const lengthIndex = product.lengths && length ? product.lengths.indexOf(length) : 0;
    if (lengthIndex > 0) {
      price += lengthIndex * 20000;
    }
    if (laceType === 'HD Lace') {
      price += 15000;
    }
    if (density === '200%') {
      price += 15000;
    } else if (density === '250%') {
      price += 32000;
    }
  }
  return price;
}
